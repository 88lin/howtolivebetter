"""Extract public tool content as data; source JavaScript is parsed, never executed.

Reference downloads belong in temp/tool-reference. Run from the repository root.
"""
from pathlib import Path
import subprocess

SCRIPT = r'''
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const directory = 'temp/tool-reference';
function source(name) {
  const filename = fs.readdirSync(directory).find(file => file.startsWith(name + '-') && file.endsWith('.js'));
  if (!filename) throw new Error('Missing reference ' + name);
  return ts.createSourceFile(filename, fs.readFileSync(path.join(directory, filename), 'utf8'), ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
}
function declarations(file) {
  const found = new Map();
  function walk(node) {
    if (ts.isVariableDeclaration(node) && ts.isIdentifier(node.name) && node.initializer) found.set(node.name.text, node.initializer);
    ts.forEachChild(node, walk);
  }
  walk(file);
  return found;
}
function literal(node) {
  if (!node) return undefined;
  if (ts.isStringLiteralLike(node)) return node.text;
  if (ts.isNumericLiteral(node)) return Number(node.text);
  if (node.kind === ts.SyntaxKind.TrueKeyword) return true;
  if (node.kind === ts.SyntaxKind.FalseKeyword) return false;
  if (node.kind === ts.SyntaxKind.NullKeyword) return null;
  if (ts.isParenthesizedExpression(node)) return literal(node.expression);
  if (ts.isPrefixUnaryExpression(node)) {
    const value = literal(node.operand);
    if (node.operator === ts.SyntaxKind.ExclamationToken) return !value;
    if (node.operator === ts.SyntaxKind.MinusToken) return -value;
  }
  if (ts.isArrayLiteralExpression(node)) return node.elements.map(literal);
  if (ts.isObjectLiteralExpression(node)) return Object.fromEntries(node.properties.map(property => {
    if (!ts.isPropertyAssignment(property)) throw new Error('Unsupported data property ' + property.getText().slice(0,80));
    return [property.name.text, literal(property.initializer)];
  }));
  if (ts.isCallExpression(node) && node.expression.getText() === 'JSON.parse') return JSON.parse(literal(node.arguments[0]));
  throw new Error('Unsupported data expression ' + node.getText().slice(0,100));
}
const index = declarations(source('index'));
const social = declarations(source('social-share-trigger'));
const quiz = declarations(source('quiz'));
const quizSource = source('quiz');
let bank;
function findBank(node) {
  if (ts.isCallExpression(node) && node.expression.getText() === 'JSON.parse') {
    try { const data = literal(node); if (Array.isArray(data) && data[0]?.id === 'q01') bank = data; } catch {}
  }
  ts.forEachChild(node, findBank);
}
findBank(quizSource);
if (!bank || bank.length !== 60) throw new Error('Expected the 60-question public bank');
const locales = ['zh','en','es','ja','ru','vi'];
const messages = {};
for (const locale of locales) {
  const file = source(locale), values = declarations(file), result = {};
  for (const statement of file.statements) {
    if (!ts.isExportDeclaration(statement) || !statement.exportClause || !ts.isNamedExports(statement.exportClause)) continue;
    for (const item of statement.exportClause.elements) {
      const key = item.name.text;
      if (!/^(life_(daily|bingo|quiz|share|actions|status|parentscloud|parentsplan)_|practice_|meditation_|pomodoro_)/.test(key)) continue;
      const arrow = values.get((item.propertyName || item.name).text);
      if (!arrow || !ts.isArrowFunction(arrow)) continue;
      let body = arrow.body;
      while (ts.isParenthesizedExpression(body)) body = body.expression;
      if (ts.isStringLiteralLike(body)) result[key] = body.text;
      else if (ts.isTemplateExpression(body)) result[key] = body.head.text + body.templateSpans.map(span => '{' + span.expression.getText().split('.').pop() + '}' + span.literal.text).join('');
    }
  }
  messages[locale] = result;
}
const copy = literal(index.get('Pu'));
const checkup = Object.fromEntries(locales.map(locale => [locale, copy[locale] || copy.en]));
const chapterImages = {};
const chapterDir = 'public/sites/howtolivebetter/images/book-chapters';
if (fs.existsSync(chapterDir)) for (const file of fs.readdirSync(chapterDir)) {
  if (/^\d{2}-.+editorial/.test(file)) chapterImages[file.slice(0,2)] = '/sites/howtolivebetter/images/book-chapters/' + file;
}
const output = `// Public text and question data extracted from howtolivebetter.net.\n// Generated by scripts/extract-tool-data.py; production bundles are never imported.\n\nexport type ToolLocale = 'zh' | 'en' | 'es' | 'ja' | 'ru' | 'vi';\nexport interface QuizQuestion { id: string; topic: string; entryId: string; zh: QuizTranslation; en: QuizTranslation; es: QuizTranslation; ja: QuizTranslation; ru: QuizTranslation; vi: QuizTranslation; }\nexport interface QuizTranslation { question: string; options: string[]; explanation: string; }\nexport interface CheckupQuestion { id: string; multiple: boolean; max?: number; options: Record<string, {chapters: Record<string, number>; keywords?: Record<string, string[]>}>; }\nexport interface CheckupCopy { [key: string]: unknown; questions: Record<string,{title:string;options:Record<string,string>}>; parents: { [key: string]: unknown; questions: Record<string,{title:string;options:Record<string,string>}>; resultTitle:string; resultLead:string; }; }\n\n`;
let out = output;
function emit(name, data, type) { out += 'export const ' + name + (type ? ': ' + type : '') + ' = ' + JSON.stringify(data, null, 2) + ';\n\n'; }
emit('quizQuestions', bank, 'QuizQuestion[]');
emit('toolMessages', messages, 'Record<ToolLocale, Record<string, string>>');
emit('dailyTasks', literal(social.get('v')), 'Array<{ id: string; chapter: string; minutes: number }>');
emit('bingoIds', literal(social.get('b')), 'string[]');
emit('checkupDefinitions', {self: literal(index.get('ac')), parents:literal(index.get('uc'))}, 'Record<"self" | "parents", CheckupQuestion[]>');
emit('checkupBaseWeights', {self:literal(index.get('oc')),parents:literal(index.get('dc'))}, 'Record<"self" | "parents", Record<string,number>>');
emit('checkupCopy', checkup, 'Record<ToolLocale, CheckupCopy>');
emit('layoffCopy', literal(index.get('Im')));
emit('chapterImages', chapterImages, 'Record<string,string>');
fs.mkdirSync('src/components/sites/howtolivebetter', {recursive:true});
fs.writeFileSync('src/components/sites/howtolivebetter/tool-data.ts', out);
process.stdout.write(JSON.stringify({quiz:bank.length,daily:literal(social.get('v')).length,locales,messages:Object.fromEntries(locales.map(locale=>[locale,Object.keys(messages[locale]).length])),bytes:Buffer.byteLength(out)})+'\n');
'''

if __name__ == '__main__':
    root = Path(__file__).resolve().parents[1]
    subprocess.run(['node', '-e', SCRIPT], cwd=root, check=True)
